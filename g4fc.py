def calculate_valve(valve_type, measured, old_thickness):
    """
    Рассчитывает необходимый размер толкателя.
    Впуск номинал: 0.20 мм, Выпуск номинал: 0.25 мм
    """
    try:
        m = float(measured.replace(',', '.'))
        old = float(old_thickness.replace(',', '.'))
    except ValueError:
        return "Ошибка: Введите корректные числа"

    if valve_type == "Впуск":
        new_size = old + (m - 0.20)
    else:
        new_size = old + (m - 0.25)
        
    return f"Требуемый толкатель: {new_size:.3f} мм"
